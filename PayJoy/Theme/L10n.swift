    static func t(_ key: String) -> String {
        let language = currentLanguage
        guard language != .system, language != .zhHans else { return key }
        return qualitySupplementalTable[language]?[key]
            ?? finalSupplementalTable[language]?[key]
            ?? table[language]?[key]
            ?? supplementalTable[language]?[key]
            ?? patternTranslation(key, language: language)
            ?? fallbackTranslation(key, language: language)
            ?? key
    }

    static func t(_ key: String, _ value: String) -> String {
        String(format: t(key), locale: Locale(identifier: currentLanguage.localeIdentifier), value)
    }

    static func format(_ key: String, _ arguments: CVarArg...) -> String {
        String(format: t(key), locale: Locale(identifier: currentLanguage.localeIdentifier), arguments: arguments)
    }

