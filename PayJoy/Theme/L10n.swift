    private static func localizedPeriodPhrase(period: String, zhHantSuffix: String, enSuffix: String, jaSuffix: String, koSuffix: String, language: AppLanguage) -> String? {
        switch language {
        case .zhHant:
            return "\(traditionalized(period))\(zhHantSuffix)"
        case .en:
            return "\(periodName(period, language: .en)) \(enSuffix)"
        case .ja:
            return "\(periodName(period, language: .ja))\(jaSuffix)"
        case .ko:
            return "\(periodName(period, language: .ko))\(koSuffix)"
        case .system, .zhHans:
            return nil
        }
    }

    private static func periodName(_ value: String, language: AppLanguage) -> String {
        switch (value, language) {
        case ("今日", .en): return "Today"
        case ("本月", .en): return "Monthly"
        case ("本年", .en), ("今年", .en): return "Yearly"
        case ("今日", .ja): return "今日"
        case ("本月", .ja): return "今月"
        case ("本年", .ja), ("今年", .ja): return "今年"
        case ("今日", .ko): return "오늘"
        case ("本月", .ko): return "이번 달"
        case ("本年", .ko), ("今年", .ko): return "올해"
        default:
            return value
        }
    }

    private static func durationTranslation(_ key: String, language: AppLanguage) -> String? {
        if key.hasSuffix("秒"), let seconds = key.dropLast().split(separator: "分").last {
            if key.contains("分") {
                let parts = key.dropLast().split(separator: "分")
                guard parts.count == 2 else { return nil }
                switch language {
                case .zhHant: return "\(parts[0])分\(parts[1])秒"
                case .en: return "\(parts[0])m \(parts[1])s"
                case .ja: return "\(parts[0])分\(parts[1])秒"
                case .ko: return "\(parts[0])분 \(parts[1])초"
                default: return nil
                }
            }
            switch language {
            case .zhHant: return "\(seconds)秒"
            case .en: return "\(seconds)s"
            case .ja: return "\(seconds)秒"
            case .ko: return "\(seconds)초"
            default: return nil
            }
        }
        return nil
    }

